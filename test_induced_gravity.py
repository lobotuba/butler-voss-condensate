VF = 1.0                                            # v_F (=3/2 on the honeycomb; units here)
LAM, NG = 0.8, 901                                  # low-energy disc around the Dirac node
_g = np.linspace(-LAM, LAM, NG) + 1e-5
_X, _Y = np.meshgrid(_g, _g, indexing="ij")
_M = (_X ** 2 + _Y ** 2) <= LAM ** 2
_KX, _KY = _X[_M], _Y[_M]
_dA = (2 * LAM / (NG - 1)) ** 2


def pi_graviton(q, Om):
    """Interband <T_+ T_+> bubble (h_+ = xx-yy graviton polarisation), T=0."""
    kx, ky = _KX, _KY
    k2x, k2y = kx + q[0], ky + q[1]
